 await page.eval('document.querySelector(".model-modal-overlay:not(.closing) #ui-confirm-ok").click()');
 await page.waitFor('window.__library.length===3 && !state.personaTemplates.custom_3');
 assert.deepEqual(await page.eval('readPersonaRevisions()'),history,'删除不动历史');
