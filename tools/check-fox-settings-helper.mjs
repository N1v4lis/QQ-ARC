import assert from 'node:assert/strict';
import {withPage} from './cdp.mjs';
await withPage({url:'http://127.0.0.1:3210/',width:1360,height:900},async p=>{
 await p.waitFor('!!state.config && !!window.qqaFoxSettingsHelper && !document.getElementById("loading-overlay")',{timeout:60000});
 await p.eval(`qqaSkin.set('minecraft');openSettingsSection('theme')`);
 await p.waitFor('qqaWineFox.state().loaded',{timeout:20000});
 const modes=await p.eval(`(async()=>{const h=qqaWineFox.helper(),out=[];for(const x of [60,300,900]){qqaWineFox.set({x:20,y:300});h.beginHelper();const move=h.helperMove(x,300);out.push(h.state().travel?.animation);h.endHelper();await move;}return out;})()`);
 await p.eval(`(()=>{const original=fetch;window.fetch=async(input,init)=>{const url=typeof input==='string'?input:input.url;if(url.includes('/api/config')&&init?.method==='POST')return new Response(JSON.stringify({ok:true,config:state.config}),{headers:{'content-type':'application/json'}});return original(input,init)}})()`);
 assert.deepEqual(modes,['walk','run','fly']);
 await p.eval(`(()=>{const h=qqaWineFox.helper(),r=document.getElementById('wine-fox-pet').getBoundingClientRect();for(let y=r.top+20;y<r.bottom;y+=12)for(let x=r.left+20;x<r.right;x+=12)if(h.helperHit({clientX:x,clientY:y})){document.body.dispatchEvent(new MouseEvent('contextmenu',{clientX:x,clientY:y,bubbles:true,cancelable:true}));return;}throw Error('找不到酒狐命中点');})()`);
 assert.equal(await p.eval(`qqaFoxSettingsHelper.state().open`),true);
 await p.eval(`qqaFoxSettingsHelper.cancel()`);
 await p.eval(`document.getElementById('card-mc').classList.remove('open');document.getElementById('mc-sfx-on').dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true}))`);
 assert.equal(await p.eval(`qqaFoxSettingsHelper.state().open`),true);
 await new Promise(r=>setTimeout(r,220));
 await p.screenshot('shots/final/fox-settings-dialog.png');
 const value=await p.eval(`document.getElementById('mc-sfx-on').checked`);
 assert.equal(await p.eval(`qqaFoxSettingsHelper.run('#mc-sfx-on','${value?'off':'on'}')`),true);
 assert.equal(await p.eval(`document.getElementById('mc-sfx-on').checked`),!value);
 assert.equal(await p.eval(`qqaMcTheme.read().sfxOn`),!value);
 assert.deepEqual(await p.eval(`qqaFoxSettingsHelper.state().history`),['travel','open','control','gesture','done']);
 assert.equal(await p.eval(`qqaWineFox.helper().state().helperBusy`),false);
 assert.equal(await p.eval(`qqaWineFox.helper().state().animation`),'idle');
 await p.eval(`void(window.numericTask=qqaFoxSettingsHelper.run('#mc-bg-opacity','43'))`);
 await p.waitFor('qqaFoxSettingsHelper.state().phase==="gesture"');
 await new Promise(r=>setTimeout(r,220));
 await p.screenshot('shots/final/fox-settings-lever.png');
 assert.equal(await p.eval(`window.numericTask`),true);
 assert.equal(await p.eval(`qqaMcTheme.read().bgOpacity`),.43);
 assert.equal(await p.eval(`qqaFoxSettingsHelper.run('#mc-bg-opacity','101')`),false);
 await p.eval(`window.lateBefore=document.getElementById('mc-bg-opacity').value;window.lateTask=qqaFoxSettingsHelper.run('#mc-bg-opacity','73');qqaFoxSettingsHelper.cancel()`);
 assert.equal(await p.eval(`window.lateTask`),false);
 assert.equal(await p.eval(`document.getElementById('mc-bg-opacity').value`),await p.eval(`window.lateBefore`));
 assert.equal(await p.eval(`document.querySelectorAll('.fox-helper-dialog').length`),0);
 console.log('酒狐设置助手：三档移动、折叠卡、真实开关与数值、重复操作、边界值及取消通过。');
});
