// 只验证图标、拉杆、导航音效及皮肤还原，不跑宠物完整互动。
import assert from 'node:assert/strict';
import { withPage } from './cdp.mjs';
await withPage({url:process.argv[2]||'http://127.0.0.1:3210/',width:1360,height:900},async page=>{
  await page.waitFor('!!window.qqaMcIcons && !!window.qqaMcTheme && !!document.querySelector(".db-icon svg") && !!document.querySelector(".dc-chart")',{timeout:15000});
  const result=await page.eval(`(async()=>{
    window.qqaSkin.set('default');
    const original=document.querySelector('#tabs .tab-ico').innerHTML;
    const chart=document.querySelector('.dc-chart');
    window.qqaSkin.set('minecraft');
    await new Promise(resolve=>requestAnimationFrame(resolve));
    const nav=[...document.querySelectorAll('#tabs .tab-ico')];
    const pixelNav=nav.length===9&&nav.every(node=>node.dataset.mcIcon&&[...node.children].every(child=>child.tagName==='rect'));
    const dashboard=[...document.querySelectorAll('.db-icon svg')].every(node=>!!node.dataset.mcIcon);
    const theme=!!document.querySelector('#theme-btn svg[data-mc-icon]');
    const host=document.createElement('div');host.id='mc-control-fixture';
    host.innerHTML='<span class="sc-ico">🎨</span><input type="checkbox" id="mc-plain-fixture" aria-label="测试复选框"><label class="switch"><input type="checkbox" id="mc-switch-fixture"><span class="track"><span class="thumb"></span></span><span>测试拉杆</span></label>';
    document.body.append(host);
    await new Promise(resolve=>requestAnimationFrame(resolve));
    const dynamicIcon=host.querySelector('.sc-ico').dataset.mcIcon;
    const input=host.querySelector('#mc-plain-fixture'),wrapped=host.querySelector('#mc-switch-fixture'),track=host.querySelector('.track'),thumb=host.querySelector('.thumb');
    const sizes=[input,track].map(node=>[getComputedStyle(node).width,getComputedStyle(node).height]);
    const off=getComputedStyle(thumb).transform;
    let changes=0;wrapped.addEventListener('change',()=>changes++);wrapped.click();input.click();
    await new Promise(resolve=>setTimeout(resolve,180));
    const on=getComputedStyle(thumb).transform;
    const functional=wrapped.checked&&input.checked&&changes===1;
    const calls=[],play=window.qqaMcTheme.playToggle;
    window.qqaMcTheme.playToggle=value=>calls.push(value);
    document.documentElement.dataset.nav='expanded';
    document.querySelector('#q-side-toggle').click();document.querySelector('#q-side-toggle').click();
    window.dispatchEvent(new KeyboardEvent('keydown',{key:'b',ctrlKey:true,bubbles:true}));
    window.qqaMcTheme.playToggle=play;
    const chartPreserved=chart?.isConnected&&!chart.hasAttribute('data-mc-icon');
    window.qqaSkin.set('default');
    const restored=document.querySelector('#tabs .tab-ico').innerHTML===original;
    const defaultSize=getComputedStyle(track).width;
    host.remove();window.qqaSkin.set('minecraft');document.documentElement.dataset.nav='expanded';
    return {pixelNav,dashboard,theme,dynamicIcon,sizes,functional,rotates:on!==off,calls,chartPreserved,restored,defaultSize};
  })()`);
  console.log(JSON.stringify(result,null,2));
  for(const key of ['pixelNav','dashboard','theme','functional','rotates','chartPreserved','restored'])assert.equal(result[key],true,key);
  assert.equal(result.dynamicIcon,'palette');
  assert.deepEqual(result.sizes,[['80px','64px'],['80px','64px']]);
  assert.deepEqual(result.calls,[false,true,false]);
  assert.equal(result.defaultSize,'38px');
  await page.waitFor('!document.querySelector("#loading-overlay")',{timeout:15000});
  await page.screenshot('shots/final/mc-icons-refactor.png');
  await page.eval('document.querySelector(\'.tab[data-tab="settings"]\').click()');
  await page.waitFor('!!document.querySelector(\'.settings-menu-item[data-section="theme"]\')',{timeout:15000});
  await page.eval('document.querySelector(\'.settings-menu-item[data-section="theme"]\').click()');
  await page.waitFor('!!document.querySelector(".th-skins")',{timeout:15000});
  await page.screenshot('shots/final/mc-levers-refactor.png');
  await page.eval('document.documentElement.dataset.theme="dark"; window.qqaMcIcons.sync()');
  assert.equal(await page.eval('document.querySelector("#theme-btn svg").dataset.mcIcon'),'moon');
  await page.screenshot('shots/final/mc-levers-refactor-dark.png');
  await page.send('Emulation.setDeviceMetricsOverride',{width:800,height:900,deviceScaleFactor:1,mobile:false});
  await page.eval('document.documentElement.dataset.nav="collapsed"');
  assert.equal(await page.eval('getComputedStyle(document.querySelector(".tab-tx")).display'),'none');
  const horizontalOverflow=await page.eval('document.documentElement.scrollWidth>innerWidth');
  assert.equal(horizontalOverflow,false,'窄窗横向溢出');
  await page.screenshot('shots/final/mc-levers-refactor-narrow.png');
  console.log('✔ 图标/动态设置、两种大拉杆、导航开关方向、默认主题还原通过');
});
